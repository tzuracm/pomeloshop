-- =============================================================================
-- Pomelo Shop — canonical SKU codes
-- =============================================================================
-- Run this in the Supabase SQL Editor AFTER 0002_pomelo_rbac.sql.
--
-- WHY
-- ---
-- The catalogue originally used the human size ("5kg", "10kg") as the primary
-- key. That is not a SKU: it is a label, it is ambiguous once two products
-- share a size, and it leaks presentation text into order line items.
--
-- This migration re-codes every existing row to the canonical form
--
--     POM-<SIZE>-<NNN>        e.g. POM-5KG-001, POM-10KG-001
--
-- and adds a CHECK constraint so future rows must follow it. New codes are
-- generated by the API (api/admin/catalogue.js) on create.
--
-- SAFETY
-- ------
--   * Idempotent: rows already matching the pattern are left untouched.
--   * Historical orders keep their original `items[].sku` values; the
--     `items[].label` field is what the UI/Excel export displays, so old
--     orders remain readable.
--   * Run the whole file in one go.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. Re-code legacy rows
-- -----------------------------------------------------------------------------
-- Derive the size token from the label ("5 kg 装" -> "5KG"), falling back to
-- "ITEM" when no size can be parsed. Sequence numbers are assigned per prefix
-- in sort_order order so the result is deterministic.
with legacy as (
  select
    sku,
    label,
    sort_order,
    'POM-' || coalesce(
      nullif(
        upper(regexp_replace(
          (regexp_match(label, '(\d+(?:\.\d+)?)\s*(kg|g|ml|l)\M', 'i'))[1] ||
          (regexp_match(label, '(\d+(?:\.\d+)?)\s*(kg|g|ml|l)\M', 'i'))[2],
          '\.', '', 'g'
        )),
        ''
      ),
      'ITEM'
    ) as prefix
  from public.pomelo_catalogue
  where sku !~ '^POM-[A-Z0-9]+(-[A-Z0-9]+)*-\d{3,}$'
),
numbered as (
  select
    sku,
    prefix || '-' || lpad(
      row_number() over (partition by prefix order by sort_order, sku)::text,
      3, '0'
    ) as new_sku
  from legacy
)
update public.pomelo_catalogue c
set sku = n.new_sku
from numbered n
where c.sku = n.sku;

-- -----------------------------------------------------------------------------
-- 2. Enforce the canonical shape going forward
-- -----------------------------------------------------------------------------
alter table public.pomelo_catalogue
  drop constraint if exists pomelo_catalogue_sku_format;

alter table public.pomelo_catalogue
  add constraint pomelo_catalogue_sku_format
  check (sku ~ '^POM-[A-Z0-9]+(-[A-Z0-9]+)*-\d{3,}$');

comment on column public.pomelo_catalogue.sku is
  'Canonical SKU code: POM-<SIZE>-<NNN> (e.g. POM-5KG-001). Generated by the API on create; immutable.';

-- -----------------------------------------------------------------------------
-- 3. Verify
-- -----------------------------------------------------------------------------
select sku, label, unit_price, sort_order, active
from public.pomelo_catalogue
order by sort_order, sku;
